"""Build deterministic, offline UI translations; reject missing languages/placeholders."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BASE_LANGUAGES = ('zh-Hans', 'hi', 'es', 'ar', 'th')
ADDITIONAL_LANGUAGES = ('ko', 'tl', 'vi')
LANGUAGES = BASE_LANGUAGES + ADDITIONAL_LANGUAGES


def read_catalog(path):
    def unique_object(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f'{path.name}: duplicate source message {key!r}')
            result[key] = value
        return result
    result = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object)
    if not isinstance(result, dict):
        raise ValueError(f'{path.name}: catalog must be an object')
    return result


def validate_translations(path, source, translations, languages):
    if not isinstance(translations, list) or len(translations) != len(languages):
        raise ValueError(f'{path.name}: missing languages for {source!r}')
    placeholders = sorted(re.findall(r'\{\d+\}', source))
    for language, translation in zip(languages, translations):
        if not isinstance(translation, str) or not translation.strip():
            raise ValueError(f'{path.name}: empty {language}: {source!r}')
        if sorted(re.findall(r'\{\d+\}', translation)) != placeholders:
            raise ValueError(f'{path.name}: placeholders changed for {language}: {source!r}')

def build():
    messages = {}
    paths = sorted((ROOT / 'static/locales').glob('*.json'))
    addition_paths = {path.name for path in (ROOT / 'static/locales/additions').glob('*.json')}
    if addition_paths - {path.name for path in paths}:
        raise ValueError(f'Additional-language catalogs have no base catalog: {sorted(addition_paths - {path.name for path in paths})!r}')
    for path in paths:
        sources = read_catalog(path)
        addition_path = path.parent / 'additions' / path.name
        if not addition_path.is_file():
            raise ValueError(f'{path.name}: missing additional-language catalog')
        additions = read_catalog(addition_path)
        if set(sources) != set(additions):
            raise ValueError(f'{path.name}: additional-language source keys differ; missing={sorted(set(sources) - set(additions))!r}; extra={sorted(set(additions) - set(sources))!r}')
        for source, translations in sources.items():
            validate_translations(path, source, translations, BASE_LANGUAGES)
            validate_translations(addition_path, source, additions[source], ADDITIONAL_LANGUAGES)
            if source in messages:
                raise ValueError(f'{path.name}: duplicate source message {source!r}; keep shared terms in one catalog')
            messages[source] = translations + additions[source]
    payload = '/* Generated by scripts/build_language_catalog.py. Do not edit. */\nwindow.CeasefireMessages = Object.freeze(' + json.dumps(messages, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + ');\n'
    return payload, len(messages)

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    payload, count = build(); target = ROOT / 'static/language-catalog.js'
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != payload:
            raise SystemExit('Language catalog needs rebuilding.')
    else:
        target.write_text(payload, encoding='utf-8', newline='\n')
    print(f'{count} UI messages, English plus {len(LANGUAGES)} complete translations each.')
