"""Build deterministic, offline UI translations; reject missing languages/placeholders."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('zh-Hans', 'hi', 'es', 'ar', 'th')

def build():
    messages = {}
    for path in sorted((ROOT / 'static/locales').glob('*.json')):
        for source, translations in json.loads(path.read_text(encoding='utf-8')).items():
            if not isinstance(translations, list) or len(translations) != len(LANGUAGES):
                raise ValueError(f'{path.name}: missing languages for {source!r}')
            placeholders = sorted(re.findall(r'\{\d+\}', source))
            for language, translation in zip(LANGUAGES, translations):
                if not isinstance(translation, str) or not translation.strip():
                    raise ValueError(f'{path.name}: empty {language}: {source!r}')
                if sorted(re.findall(r'\{\d+\}', translation)) != placeholders:
                    raise ValueError(f'{path.name}: placeholders changed for {language}: {source!r}')
            if source in messages:
                raise ValueError(f'{path.name}: duplicate source message {source!r}; keep shared terms in one catalog')
            messages[source] = translations
    payload = '/* Generated by scripts/build_language_catalog.py. Do not edit. */\nwindow.CeasefireMessages = Object.freeze(' + json.dumps(messages, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + ');\n'
    return payload, len(messages)

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    payload, count = build(); target = ROOT / 'static/language-catalog.js'
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != payload:
            raise SystemExit('Language catalog needs rebuilding.')
    else:
        target.write_text(payload, encoding='utf-8', newline='\n')
    print(f'{count} UI messages, English plus {len(LANGUAGES)} complete translations each.')
