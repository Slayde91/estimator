const {fillProjectDetails}=require('./project_actions.cjs');
const {chromium, expect: baseExpect} = require('@playwright/test');
const expect = baseExpect.configure({timeout:30000});
const {spawn} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {openProjectSection,clickProjectControl} = require('./project_actions.cjs');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, '.runtime/browser-qa', `swms-${Date.now()}`);
fs.mkdirSync(output, {recursive:true});
const checks = [];
async function run(edition) {
  const directory = path.join(output, edition);
  const server = spawn(process.env.CEASEFIRE_PYTHON || 'python', [path.join(__dirname,'swms_fixture.py'),'--directory',directory,'--edition',edition], {cwd:root,windowsHide:true});
  let logs = '', browser;
  server.stderr.on('data', value => logs += value);
  try {
    const info = await new Promise((resolve,reject) => {
      let data = ''; const timer = setTimeout(()=>reject(Error(logs || 'Fixture timeout')),120000);
      server.stdout.on('data', value => {data += value; if(data.includes('\n')) {clearTimeout(timer);resolve(JSON.parse(data.split('\n')[0]));}});
      server.once('error',reject); server.once('exit',code=>{clearTimeout(timer);reject(Error(`Fixture exited ${code}`));});
    });
    browser = await chromium.launch({headless:true});
    const page = await browser.newPage({viewport:{width:1575,height:1000}}), errors = [], external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if(!request.url().startsWith('http://127.0.0.1:') && !request.url().startsWith('data:')) external.push(request.url()); });
    const idle = () => page.waitForFunction(()=>{const value=window.CeasefireDesktop?.status();return value?.ready && !value.busy;});
    await page.goto(`http://127.0.0.1:${info.port}/`); await idle();
    await page.getByRole('button',{name:'Estimates',exact:true}).click();
    await fillProjectDetails(page,{'client':'Example builder'}); await fillProjectDetails(page,{'site-address':'10 Test Street'});
    const firstSave=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/project/save-as');
    await clickProjectControl(page,'Save');assert.equal((await firstSave).status(),200);await idle();
    const projectNumber = await page.locator('#project-no').inputValue();
    await openProjectSection(page, 'documentation');
    const documentRow = page.locator('#documentation-pdf-rows tr').filter({hasText:'Safe Work Method Statement'});
    await documentRow.locator('.documentation-download-button').click();
    const host = page.locator('#swms-root'); await expect(host).toBeVisible();
    await host.getByRole('button',{name:'New SWMS',exact:true}).click();
    await expect(host.getByLabel('Job Reference',{exact:true})).toHaveValue(projectNumber);
    await expect(host.getByLabel('Job Reference',{exact:true})).toHaveAttribute('readonly','');
    await expect(host.getByLabel('Project Address',{exact:true})).toHaveValue('10 Test Street');
    await host.getByLabel('Document title',{exact:true}).fill(`SWMS ${edition}`);
    await expect(host.getByLabel('Status',{exact:true})).toHaveCount(0);
    await expect(host.locator('.swms-people .swms-person')).toHaveCount(0);
    await expect(host.locator('.swms-step-table tbody tr')).toHaveCount(0);
    for (const kind of ['Protective Coatings','Passive Firestopping','Installation of Passive Fire Protection Works']) await expect(host.getByLabel(kind,{exact:true})).not.toBeChecked();
    await host.getByLabel('Protective Coatings',{exact:true}).check();
    await host.getByLabel('Passive Firestopping',{exact:true}).check();
    await host.getByLabel('Installation of Passive Fire Protection Works',{exact:true}).check();
    await expect(host.locator('.swms-step-table tbody tr')).toHaveCount(45);
    const reviewerSection=host.locator(':scope > details').filter({has:page.locator(':scope > summary').filter({hasText:/^Person\/s responsible for reviewing SWMS$/})});
    await reviewerSection.locator(':scope > summary').click();
    const addStyle=button=>button.evaluate(item=>{const css=getComputedStyle(item);return {width:css.width,height:css.height,background:css.backgroundColor,color:css.color,padding:css.padding,icon:item.classList.contains('icon-only'),symbol:item.querySelector('.button-symbol')?.textContent};});
    const personStyle=await addStyle(reviewerSection.getByRole('button',{name:'Add person',exact:true}));
    for(const add of await host.getByRole('button',{name:'Add job step',exact:true}).all())assert.deepEqual(await addStyle(add),personStyle,'Add job step uses the same square + control as Add person');
    await reviewerSection.locator(':scope > summary').click();
    await expect(host.getByLabel('Template ID',{exact:true})).toHaveCount(0);
    await expect(host.getByLabel('Template Version',{exact:true})).toHaveCount(0);
    await expect(host.locator('summary').filter({hasText:/^Employees Sign-Off/})).toHaveCount(0);
    await expect(host.getByRole('button',{name:'Back to statements',exact:true})).toHaveClass(/icon-only/);
    await host.locator('summary').filter({hasText:'Risk Matrix and High Risk Work'}).click();
    const falls = 'Risk of falls from greater than 2 metres';
    const electrical = 'Work on or near energised electrical installations or services';
    await host.getByLabel(falls,{exact:true}).check();
    await expect(host.locator('.swms-high-risk-tables tbody tr')).toHaveCount(4);
    await host.locator('.swms-high-risk-tables > details > summary').first().evaluate(element=>element.scrollIntoView({block:'start'}));
    await page.evaluate(()=>window.scrollBy(0,-170));
    await page.screenshot({path:path.join(directory,'swms-high-risk-table.png')});
    const fallsControl = host.getByLabel(`${falls} item 1 controls`,{exact:true});
    async function assertEvenStep(rowInput) {
      await expect.poll(() => rowInput.evaluate(input => {
        const row = input.closest('tr');
        const fields = [1,2,4].map(column => row.cells[column].querySelector('textarea'));
        return fields.every(field => field.clientHeight >= field.scrollHeight &&
          field.getBoundingClientRect().height === fields[0].getBoundingClientRect().height);
      })).toBe(true);
    }
    assert.match(await fallsControl.inputValue(), /ticketed scaffolder/);
    await assertEvenStep(fallsControl);
    await fallsControl.fill('Retained site control');
    await host.getByLabel(falls,{exact:true}).uncheck();
    await expect(host.locator('.swms-high-risk-tables tbody tr')).toHaveCount(0);
    await host.getByLabel(falls,{exact:true}).check();
    await expect(fallsControl).toHaveValue('Retained site control');
    await host.getByLabel(electrical,{exact:true}).check();
    const blankControl = host.getByLabel(`${electrical} item 1 controls`,{exact:true});
    const smallHeight = (await blankControl.boundingBox()).height;
    assert.ok(smallHeight <= 45, `Blank step is one line (${smallHeight}px)`);
    await blankControl.fill('Electrical review\nLine two\nLine three\nLine four');
    assert.ok((await blankControl.boundingBox()).height > smallHeight);
    await assertEvenStep(blankControl);
    const narrow = {width:1101,height:884}, wide = page.viewportSize();
    await page.setViewportSize(narrow);
    await assertEvenStep(fallsControl);
    await page.setViewportSize(wide);
    await blankControl.fill('Short');
    await assertEvenStep(blankControl);
    assert.equal((await blankControl.boundingBox()).height,smallHeight);
    await blankControl.fill('Electrical review\nLine two\nLine three\nLine four');
    await host.getByLabel('NA',{exact:true}).check();
    await expect(host.locator('.swms-high-risk-tables tbody tr')).toHaveCount(0);
    await host.locator('summary').filter({hasText:'Risk Matrix and High Risk Work'}).click();
    await host.locator('summary').filter({hasText:/^Reviews$/}).click();
    const reviewTops = await host.locator('.swms-review-grid input').evaluateAll(inputs=>inputs.map(input=>Math.round(input.getBoundingClientRect().top)));
    assert.equal(new Set(reviewTops).size,1);
    await host.locator('summary').filter({hasText:/^Reviews$/}).click();
    const additionalSection = host.locator(':scope > details').filter({has:page.locator(':scope > summary').filter({hasText:/^Additional Job Steps$/})});
    await additionalSection.locator(':scope > summary').click();
    await additionalSection.getByLabel('Are there additional job steps to consider?',{exact:true}).selectOption('Yes');
    await additionalSection.getByRole('button',{name:'Add job step',exact:true}).click();
    const additionalControl = host.getByLabel('Additional Job Steps item 1 controls',{exact:true});
    assert.ok((await additionalControl.boundingBox()).height <= 45);
    await additionalControl.fill('Saved additional control\nLine two\nLine three\nLine four\nLine five');
    await additionalSection.locator(':scope > summary').click();
    await host.locator('.swms-signature:not(.swms-contact-signature)').first().getByRole('button',{name:'Draw signature',exact:true}).click();
    const pad = page.getByLabel('Signature drawing pad'), rect = await pad.boundingBox();
    const padClear = page.getByRole('dialog').getByRole('button',{name:'Clear pad',exact:true});
    const artwork = locator => locator.locator('svg path').evaluateAll(paths=>paths.map(p=>p.getAttribute('d')));
    assert.deepEqual(await artwork(padClear),await artwork(page.locator('#penetration-clear')));
    await page.mouse.move(rect.x+15,rect.y+20); await page.mouse.down(); await page.mouse.move(rect.x+45,rect.y+50,{steps:3}); await page.mouse.up();
    await padClear.click();
    await expect(page.getByRole('dialog').getByRole('button',{name:'Insert signature',exact:true})).toBeDisabled();
    await page.mouse.move(rect.x+30,rect.y+120); await page.mouse.down(); await page.mouse.move(rect.x+90,rect.y+45,{steps:6}); await page.mouse.move(rect.x+160,rect.y+125,{steps:6}); await page.mouse.up();
    await page.getByRole('dialog').getByRole('button',{name:'Insert signature',exact:true}).click();
    await expect(host.getByRole('img',{name:'Project manager drawn signature'})).toBeVisible();
    assert.deepEqual(await artwork(host.getByRole('button',{name:'Clear signature',exact:true}).first()),await artwork(page.locator('#penetration-clear')));
    await host.locator('summary').filter({hasText:'Form Attachments'}).click();
    await page.evaluate(() => {
      const original = FileReader.prototype.readAsDataURL;
      FileReader.prototype.readAsDataURL = function(file) {
        window.releaseSWMSRead = () => { FileReader.prototype.readAsDataURL = original; original.call(this,file); };
      };
    });
    await host.getByLabel('Add files',{exact:true}).setInputFiles({name:'pixel.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAIAAACQd1PeAAAADElEQVR4nGP4//8/AAX+Av4N70a4AAAAAElFTkSuQmCC','base64')});
    await expect(host.getByRole('button',{name:'Save',exact:true})).toBeDisabled();
    await expect(host.getByRole('button',{name:'Download PDF',exact:true})).toBeDisabled();
    assert.equal(await page.evaluate(()=>window.CeasefireSWMS.hasPendingOperation()),true);
    assert.equal(await page.evaluate(async()=>{try{await window.CeasefireSWMS.completeProjectSnapshot();return false;}catch{return true;}}),true);
    await page.evaluate(()=>window.releaseSWMSRead());
    await expect(host.getByText('pixel.png',{exact:true})).toBeVisible();
    await expect(host.getByRole('button',{name:'Save',exact:true})).toBeEnabled();
    await host.getByLabel('Add files',{exact:true}).setInputFiles({name:'over-budget.pdf',mimeType:'application/pdf',buffer:Buffer.alloc(9.5*1024*1024)});
    await expect(host.locator('.swms-message')).toContainText('12 MiB SWMS storage budget');
    await expect(host.getByText('over-budget.pdf',{exact:true})).toHaveCount(0);
    await expect(host.getByRole('button',{name:'Save',exact:true})).toBeEnabled();
    await host.getByRole('button',{name:'Save',exact:true}).click();
    await expect(host.locator('.swms-message')).toContainText('Saved.');
    const saveResponse = page.waitForResponse(response=>/\/api\/project\/save(?:-as)?$/.test(new URL(response.url()).pathname));
    await page.locator('#header-project-actions').getByRole('button',{name:'Save',exact:true}).click();
    assert.equal((await saveResponse).status(),200); await idle();
    const saved = JSON.parse(fs.readFileSync(info.project,'utf8'));
    assert.equal(saved.swms.documents[0].fields.work_types.length,3);
    assert.ok(saved.swms.documents[0].fields.manager_signature.strokes.length);
    assert.equal(saved.swms.documents[0].fields.attachments[0].name,'pixel.png');
    assert.equal(saved.swms.documents[0].fields.high_risk_steps[falls][0].controls,'Retained site control');
    assert.match(saved.swms.documents[0].fields.high_risk_steps[electrical][0].controls,/Electrical review/);
    const downloadResponse = page.waitForResponse(response=>response.url().endsWith('/api/swms/issue') && response.request().method()==='POST');
    await host.getByRole('button',{name:'Download PDF',exact:true}).click();
    const response = await downloadResponse, result = await response.json();
    assert.equal(response.status(),200,JSON.stringify(result)); assert.equal(result.saved,true);
    assert.ok(result.path.startsWith(directory)); assert.equal(fs.readFileSync(result.path).subarray(0,5).toString(),'%PDF-');
    await expect(host.locator('.swms-message')).toContainText('SWMS PDF saved.'); await idle();
    assert.equal(await page.evaluate(()=>JSON.parse(window.CeasefireSWMS.projectFingerprint()).editor.pendingIssue),null);
    // A confirmed export ends its retry receipt; a later company change must
    // generate a fresh export without reopening or editing this statement.
    const company = await (await page.request.get(`http://127.0.0.1:${info.port}/api/company-settings`)).json();
    const updatedCompany = await page.request.post(`http://127.0.0.1:${info.port}/api/company-settings`,{data:{...company,name:'UPDATED SWMS COMPANY'}});
    assert.equal(updatedCompany.status(),200,await updatedCompany.text());
    const secondResponse = page.waitForResponse(response=>response.url().endsWith('/api/swms/issue') && response.request().method()==='POST');
    await host.getByRole('button',{name:'Download PDF',exact:true}).click();
    const second = await secondResponse;
    assert.equal(second.status(),200,await second.text());
    await expect(host.locator('.swms-message')).toContainText('SWMS PDF saved.'); await idle();
    await page.evaluate(()=>{window.originalSWMSDownload=window.CeasefireDownloads.save;window.CeasefireDownloads.save=async()=>({cancelled:true});});
    await host.getByRole('button',{name:'Download PDF',exact:true}).click();
    await expect(host.locator('.swms-message')).toContainText('PDF download cancelled.');
    assert.ok(await page.evaluate(()=>JSON.parse(window.CeasefireSWMS.projectFingerprint()).editor.pendingIssue));
    await page.evaluate(()=>{window.CeasefireDownloads.save=window.originalSWMSDownload;});
    await host.getByRole('button',{name:'Back to statements',exact:true}).click();
    await host.getByRole('button',{name:'Open',exact:true}).click();
    await expect(host.getByRole('img',{name:'Project manager drawn signature'})).toBeVisible();
    await expect(host.locator('.swms-step-table tbody tr')).toHaveCount(46);
    await additionalSection.locator(':scope > summary').click();
    await expect(additionalControl).toHaveValue('Saved additional control\nLine two\nLine three\nLine four\nLine five');
    await expect.poll(()=>additionalControl.evaluate(input=>input.clientHeight >= input.scrollHeight)).toBe(true);
    await assertEvenStep(additionalControl);
    assert.ok((await additionalControl.boundingBox()).height > 80,'Saved additional controls expand when their collapsed parent opens');
    await page.screenshot({path:path.join(directory,'swms-editor.png'),fullPage:false});
    // Raw user text is rendered through DOM text/value properties, never HTML.
    await host.getByLabel('Document title',{exact:true}).fill('<img src=x onerror=alert(1)>');
    await host.getByRole('button',{name:'Save',exact:true}).click(); await expect(host.locator('.swms-message')).toContainText('Saved.');
    const lastSavedTitle = '<img src=x onerror=alert(1)>';
    const title = host.getByLabel('Document title',{exact:true});
    await title.fill('Unsaved site changes');
    const home = page.locator('nav [data-view="home"]');
    await home.click();
    const discard = page.getByRole('dialog',{name:'Discard the current SWMS?'});
    await discard.getByRole('button',{name:'Cancel',exact:true}).click();
    await expect(title).toHaveValue('Unsaved site changes');
    await expect(page.locator('#app-message')).toContainText('Save or discard the current SWMS edit before changing views.');
    await home.click();
    await discard.getByRole('button',{name:'Yes',exact:true}).click();
    await expect(page.locator('#view-home')).toBeVisible();
    await openProjectSection(page,'swms');
    await expect(host.getByRole('heading',{name:lastSavedTitle,exact:true})).toBeVisible();
    await host.getByRole('button',{name:'Open',exact:true}).click();
    await expect(title).toHaveValue(lastSavedTitle);
    await host.getByRole('button',{name:'Back to statements',exact:true}).click();
    await expect(host.getByRole('heading',{name:'<img src=x onerror=alert(1)>',exact:true})).toBeVisible();
    assert.equal(await host.locator('img').count(),0);
    // Saved ink is selected only by an explicit click in each document.
    const signatureProfiles=require('./personal_signature_profiles.cjs');
    await signatureProfiles(page, edition);
    assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
    checks.push(`${edition}: Documents entry, project defaults, 45 work steps, conditional high-risk tables and retained edits, compact expanding rows and saved additional controls grow on parent reopen, ten reviews on one row, removed legacy UI, back icon, drawn signature, delayed attachment lock and encoded budget, save/reopen, portable project, real PDF download after company change, cleared successful export receipt and retained cancellation receipt, escaped text, no external location requests`);
  } catch(error) { fs.mkdirSync(directory,{recursive:true});fs.writeFileSync(path.join(directory,'server.log'),logs);throw error; }
  finally { await browser?.close(); server.kill(); }
}
(async()=>{ await run('full'); await run('standard'); checks.push(await require('./swms_people_defaults.cjs')(root,output)); checks.push(await require('./swms_contact_signature.cjs')(root,output)); fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({checks},null,2)); console.log(JSON.stringify({checks,output})); })().catch(error=>{console.error(error);process.exitCode=1;});
